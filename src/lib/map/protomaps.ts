const VENTURE_FLAVORS: Record<MapTheme, Flavor> = {
  light: ventureLight,
  dark: ventureDark,
};

export function createProtomapsStyle(theme: MapTheme): StyleSpecification {
  const flavor = VENTURE_FLAVORS[theme];
  return {
    version: 8,
    metadata: { 'venture:theme': theme },
    sources: {
      protomaps: {
        type: 'vector',
        tiles: [PROTOMAPS_TILES_URL],
        attribution: '© <a href="https://openstreetmap.org/copyright" target="_blank" rel="noopener noreferrer">OpenStreetMap</a> contributors · Protomaps',
      },
    },
    layers: layers('protomaps', flavor, { lang: 'en' }),
    glyphs: 'https://protomaps.github.io/basemaps-assets/fonts/{fontstack}/{range}.pbf',
    sprite: `https://protomaps.github.io/basemaps-assets/sprites/v4/${theme}`,
  };
}
